local function hex_dump(str)
	local dump = {}
	for i = 1, #str do
		table.insert(dump, string.format("%02x", str:byte(i)))
	end
	return table.concat(dump, " ")
end

print("<-- full_response Hex: " .. hex_dump(full_response))

