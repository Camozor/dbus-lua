local IS_LITTLE_ENDIAN = 0x6c -- 'l' for little endian
local METHOD_CALL = 0x01
local FLAGS_NONE = 0x00
local PROTOCOL_VERSION = 0x01

local SERIAL = 0x01

local function compute_header()
	return wire.encode_byte(IS_LITTLE_ENDIAN)
		.. wire.encode_byte(METHOD_CALL)
		.. wire.encode_byte(FLAGS_NONE)
		.. wire.encode_byte(PROTOCOL_VERSION)
		.. wire.encode_uint32(0x00) -- TODO  Body length in bytes
		.. wire.encode_uint32(SERIAL)
end

